import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const backend = fileURLToPath(new URL('../../backend/', import.meta.url));
const output = new URL('../src/app/core/api.generated.ts', import.meta.url);
const schema = spawnSync('uv', ['run', '--locked', 'python', '-c',
  'import json; from app.main import app; print(json.dumps(app.openapi()))'],
  { cwd: backend, encoding: 'utf8' });
if (schema.error) throw schema.error;
if (schema.status !== 0) throw new Error(schema.stderr);
const types = '// Generated by npm run gen:api.\n' + astToString(await openapiTS(JSON.parse(schema.stdout)));
if (process.argv.includes('--check')) {
  const existing = await readFile(output, 'utf8');
  if (existing.replaceAll('\r\n', '\n') !== types) throw new Error('API schema changed. Run npm run gen:api.');
} else {
  await mkdir(new URL('.', output), { recursive: true });
  await writeFile(output, types);
}
